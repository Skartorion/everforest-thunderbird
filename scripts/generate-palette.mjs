import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { runInNewContext } from "node:vm";
const root = fileURLToPath(new URL("../", import.meta.url));
const sandbox = {};
runInNewContext(readFileSync(resolve(root, "palette.js"), "utf8"), sandbox);
const css = "/* Generated by npm run generate from palette.js; do not edit. */\n:root {\n" +
  Object.entries(sandbox.EVERFOREST_PALETTE).map(([key, value]) =>
    `  --ef-${key.replaceAll("_", "-")}: ${value};`).join("\n") + "\n}\n";
const path = resolve(root, "palette.css");
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== css) throw Error("Run npm run generate; palette.css is stale");
} else {
  writeFileSync(path, css);
}
